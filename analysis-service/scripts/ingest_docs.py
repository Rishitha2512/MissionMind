def main():
    output_dir = Path(__file__).resolve().parent.parent.parent / "data" / "processed"
    output_dir.mkdir(parents=True, exist_ok=True)
    output_path = output_dir / "chunks.json"

    all_chunks = []
    for doc in DOCUMENTS:
        chunks = chunk_document(
            doc_id=doc["doc_id"],
            doc_title=doc["doc_title"],
            source_url=doc["source_url"],
            text=doc["text"],
            chunk_size_tokens=150,
            chunk_overlap_tokens=30,
        )
        all_chunks.extend(chunks)

    save_chunks(all_chunks, output_path)
    print(f"[OK] Generated {len(all_chunks)} chunks from {len(DOCUMENTS)} documents.")
    print(f"[OK] Saved chunks to {output_path}")


if __name__ == "__main__":
    main()
